#!/usr/bin/env python3
"""Write Materials/bom_datasheets/README.md: every orderable BOM line with its Digi-Key PN,
lifecycle note, datasheet file(s) and verification result. Prints a summary.

    python3 datasheet_index.py
"""
import os

from export_bom import rows
from parts import DATASHEETS, DIGIKEY

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DIR = os.path.join(ROOT, "Materials", "bom_datasheets")


def main():
    os.makedirs(DIR, exist_ok=True)
    rs, _ = rows()
    seen, lines = {}, []
    for board, refs, qty, val, role, mfr, mpn, status, note in rs:
        if mfr == "any":
            continue
        for m in [x.strip() for x in mpn.replace(" / ", ",").split(",")]:
            if m.startswith("-"):                       # "-07100KL" shorthand in the DNP line
                m = "RC0603FR" + m
            seen.setdefault(m, [mfr, [], status])[1].append(f"{board} {refs}")
    n_ok = n_open = n_none = 0
    for m, (mfr, where, status) in seen.items():
        dk, life = DIGIKEY.get(m, ("", "no Digi-Key PN recorded"))
        docs = DATASHEETS.get(m, [])
        files = []
        for f, res in docs:
            exists = os.path.exists(os.path.join(DIR, f))
            files.append(f"[{os.path.basename(f)}]({f})" + ("" if exists else " (missing)"))
        result = " / ".join(r for _, r in docs) if docs else "no datasheet yet"
        if not docs:
            n_none += 1
        elif "OPEN" in result:
            n_open += 1
        else:
            n_ok += 1
        flag = " **⚠**" if life and life not in ("bulk",) else ""
        lines.append(f"| `{m}` | {mfr} | {', '.join(where)} | {'`'+dk+'`' if dk else '—'} | {life}{flag} | "
                     f"{'<br>'.join(files) or '—'} | {result} |")
    with open(os.path.join(DIR, "README.md"), "w") as f:
        f.write("# BOM datasheets and part verification\n\n"
                "One row per orderable part (generated by `tools/datasheet_index.py` from `tools/parts.py`). "
                "Drop each datasheet here as `<MPN>_<maker>_<kind>.pdf`, add it to `DATASHEETS` in `parts.py` with "
                "what it confirmed, and regenerate. ⚠ = lifecycle / availability problem to resolve before ordering.\n\n"
                f"Status: {n_ok} verified, {n_open} partly verified (OPEN items), {n_none} without a datasheet.\n\n"
                "| MPN | Maker | Used on | Digi-Key PN | Lifecycle / availability | Datasheet | Verification |\n"
                "|---|---|---|---|---|---|---|\n" + "\n".join(lines) + "\n")
    print(f"{len(seen)} parts: {n_ok} verified, {n_open} partly verified, {n_none} without a datasheet")


if __name__ == "__main__":
    main()
