#!/usr/bin/env python3
"""Generate FC/Drone_1S_FC.kicad_sch (KiCad 7 file format) from fc_design.py.

Every symbol pin gets a short wire stub and a net label (GND as a power symbol); no wires between parts, so the
connectivity is exactly fc_design.build_nets(). Parts are grouped in functional blocks and packed in rows by their
real size (symbol body + stubs + labels). Template: PicoBalancer/tools/gen_schematic.py.

Symbols: KD_* from ../../Libraries (generated by Libraries/tools/gen_lib.py), stock symbols from the installed
KiCad library (KiCad 10 on Windows, /usr/share/kicad/symbols on Linux). Derived stock symbols ("extends") are
flattened, because a schematic's lib_symbols must hold complete symbols.
"""
import os
import re
import sys

import importlib

from design import SHARED_LIBS, uid

# board: gen_schematic.py [fc|deck]  (fc_design.py / deck_design.py)
_M = importlib.import_module({"fc": "fc_design", "deck": "deck_design"}[(sys.argv[1:] or ["fc"])[0]])
BOM, DATE, DNP, NO_CONNECT, PINMAP, PROJECT, REVISION, VALUES, build_nets = (
    _M.BOM, _M.DATE, _M.DNP, _M.NO_CONNECT, _M.PINMAP, _M.PROJECT, _M.REVISION, _M.VALUES, _M.build_nets)
SCH = _M.SCH

HERE = os.path.dirname(os.path.abspath(__file__))
PRJ = os.path.dirname(HERE)
KD = os.path.normpath(os.path.join(PRJ, SHARED_LIBS))
STOCK = next(p for p in ("C:/Program Files/KiCad/10.0/share/kicad/symbols", "C:/Program Files/KiCad/9.0/share/kicad/symbols",
                         "/usr/share/kicad/symbols") if os.path.isdir(p))
ROOT = uid(SCH.get("root", f"{PROJECT}-root-sheet"))
G = 2.54
STUB = 2.54


# ---------------------------------------------------------------------------
# Library symbols
# ---------------------------------------------------------------------------
_libcache = {}


def _block(txt, start):
    depth = 0
    for i in range(start, len(txt)):
        if txt[i] == "(":
            depth += 1
        elif txt[i] == ")":
            depth -= 1
            if depth == 0:
                return txt[start:i + 1]
    raise ValueError("unbalanced")


def find_symbol(lib, name):
    path = os.path.join(KD if lib.startswith("KD_") else STOCK, f"{lib}.kicad_sym")
    txt = _libcache.setdefault(path, open(path, encoding="utf8").read())
    m = re.search(r'\n\s*\(symbol "%s"\s' % re.escape(name), txt)
    if not m:
        raise KeyError(f"{lib}:{name}")
    return _block(txt, m.start() + txt[m.start():].index("("))


def lib_symbol_text(lib_id):
    lib, name = lib_id.split(":")
    body = find_symbol(lib, name)
    ext = re.search(r'\(extends "([^"]+)"\)', body)
    if ext:                                   # flatten: parent graphics / pins under the child's name and fields
        parent = find_symbol(lib, ext.group(1))
        props = re.findall(r'\(property "[^"]+".*?\n\s*\)', body, re.S)
        pbody = parent
        for pr in props:
            key = re.match(r'\(property "([^"]+)"', pr).group(1)
            pm = re.search(r'\(property "%s".*?\n\s*\)' % re.escape(key), pbody, re.S)
            if pm:
                pbody = pbody[:pm.start()] + pr + pbody[pm.end():]
        body = pbody.replace(f'(symbol "{ext.group(1)}_', f'(symbol "{name}_').replace(
            f'(symbol "{ext.group(1)}"', f'(symbol "{name}"', 1)
    return body.replace(f'(symbol "{name}"', f'(symbol "{lib_id}"', 1)


PIN_RE = re.compile(r'\(pin\s+(\w+)\s+\w+\s+\(at\s+([-\d.]+)\s+([-\d.]+)\s+(\d+)\)\s+\(length\s+([-\d.]+)\)'
                    r'.*?\(number\s+"([^"]*)"', re.S)


def lib_pins(lib_id):
    """pin number -> (x, y, angle) in symbol (y-up) coordinates."""
    return {m.group(6): (float(m.group(2)), float(m.group(3)), int(m.group(4)))
            for m in PIN_RE.finditer(lib_symbol_text(lib_id))}


# ---------------------------------------------------------------------------
# Schematic items
# ---------------------------------------------------------------------------
items, lib_ids, pwr = [], set(), [0]


def fmt(v):
    return f"{round(v, 4):g}"


def pin_world(sx, sy, px, py, pang):
    out = {0: (-1, 0), 180: (1, 0), 90: (0, 1), 270: (0, -1)}[pang]
    return sx + px, sy - py, out


def place_symbol(ref, lib_id, value, footprint, x, y, dnp=False, ref_at=None, val_at=None, hide_ref=False):
    lib_ids.add(lib_id)
    pins = lib_pins(lib_id)
    rx, ry = ref_at or (x, y - 3)
    vx, vy = val_at or (x, y + 3)
    hide = " hide" if hide_ref else ""
    props = [
        f'    (property "Reference" "{ref}" (at {fmt(rx)} {fmt(ry)} 0)\n      (effects (font (size 1.27 1.27)){hide})\n    )',
        f'    (property "Value" "{value}" (at {fmt(vx)} {fmt(vy)} 0)\n      (effects (font (size 1.27 1.27)){hide if ref.startswith("#") else ""})\n    )',
        f'    (property "Footprint" "{footprint}" (at {fmt(x)} {fmt(y)} 0)\n      (effects (font (size 1.27 1.27)) hide)\n    )',
        f'    (property "Datasheet" "~" (at {fmt(x)} {fmt(y)} 0)\n      (effects (font (size 1.27 1.27)) hide)\n    )',
    ]
    pin_lines = "\n".join(f'    (pin "{n}" (uuid {uid(f"pin-{ref}-{n}")}))' for n in pins)
    virt = ref.startswith("#")
    items.append(
        f'  (symbol (lib_id "{lib_id}") (at {fmt(x)} {fmt(y)} 0) (unit 1)\n'
        f'    (in_bom {"no" if virt else "yes"}) (on_board {"no" if virt else "yes"}) (dnp {"yes" if dnp else "no"})\n'
        f'    (uuid {uid(f"sym-{ref}")})\n' + "\n".join(props) + "\n" + pin_lines + "\n"
        f'    (instances\n      (project "{PROJECT}"\n        (path "/{ROOT}" (reference "{ref}") (unit 1))\n      )\n    )\n  )')
    return {n: pin_world(x, y, *p) for n, p in pins.items()}


def wire(x1, y1, x2, y2):
    items.append(f'  (wire (pts (xy {fmt(x1)} {fmt(y1)}) (xy {fmt(x2)} {fmt(y2)}))\n'
                 f'    (stroke (width 0) (type default))\n    (uuid {uid(f"w{x1:.3f},{y1:.3f},{x2:.3f},{y2:.3f}")})\n  )')


def label(name, x, y, out):
    ang = {(-1, 0): 180, (1, 0): 0, (0, -1): 90, (0, 1): 270}[out]
    just = "right" if ang in (180, 270) else "left"
    items.append(f'  (label "{name}" (at {fmt(x)} {fmt(y)} {ang}) (fields_autoplaced)\n'
                 f'    (effects (font (size 1.27 1.27)) (justify {just} bottom))\n'
                 f'    (uuid {uid(f"lbl{name}{x:.3f},{y:.3f}")})\n  )')


def no_connect(x, y):
    items.append(f'  (no_connect (at {fmt(x)} {fmt(y)}) (uuid {uid(f"nc{x:.3f},{y:.3f}")}))')


def gnd(x, y, out):
    """GND symbol at a stub end; its bar points away from the part (rotation by stub direction)."""
    pwr[0] += 1
    rot = {(0, 1): 0, (-1, 0): 270, (1, 0): 90, (0, -1): 180}[out]
    ref = f"#PWR{pwr[0]:03d}"
    lib_ids.add("power:GND")
    items.append(
        f'  (symbol (lib_id "power:GND") (at {fmt(x)} {fmt(y)} {rot}) (unit 1)\n'
        f'    (in_bom no) (on_board no) (dnp no)\n    (uuid {uid("sym-" + ref)})\n'
        f'    (property "Reference" "{ref}" (at {fmt(x)} {fmt(y + 6)} 0)\n      (effects (font (size 1.27 1.27)) hide)\n    )\n'
        f'    (property "Value" "GND" (at {fmt(x)} {fmt(y + 3.8)} 0)\n      (effects (font (size 1.27 1.27)) hide)\n    )\n'
        f'    (property "Footprint" "" (at {fmt(x)} {fmt(y)} 0)\n      (effects (font (size 1.27 1.27)) hide)\n    )\n'
        f'    (property "Datasheet" "" (at {fmt(x)} {fmt(y)} 0)\n      (effects (font (size 1.27 1.27)) hide)\n    )\n'
        f'    (pin "1" (uuid {uid("pin-" + ref)}))\n'
        f'    (instances\n      (project "{PROJECT}"\n        (path "/{ROOT}" (reference "{ref}") (unit 1))\n      )\n    )\n  )')


def pwr_flag(x, y, net):
    pwr[0] += 1
    ref = f"#FLG{pwr[0]:03d}"
    place_symbol(ref, "power:PWR_FLAG", "PWR_FLAG", "", x, y, ref_at=(x, y - 5), val_at=(x, y - 3.2), hide_ref=True)
    wire(x, y, x, y + G)
    if net == "GND":
        gnd(x, y + G, (0, 1))
    else:
        label(net, x, y + G, (0, 1))


def note(txt, x, y, size=1.27):
    t = txt.replace('"', "'").replace("\n", "\\n")
    items.append(f'  (text "{t}" (at {fmt(x)} {fmt(y)} 0)\n    (effects (font (size {size:g} {size:g})) (justify left top))\n'
                 f'    (uuid {uid("note" + txt[:60])})\n  )')


# ---------------------------------------------------------------------------
# Parts, sizes, packing
# ---------------------------------------------------------------------------
def parts():
    out = {}
    for refs, val, sym, fp, _role in BOM:
        if sym == "-":
            continue
        for r in refs.split():
            out[r] = (sym, VALUES.get(r, val.split(" (")[0].split(",")[0]), fp)
    return out


NETMAP = {}
for _net, _conns in build_nets().items():
    for _r, _p in _conns:
        NETMAP[(_r, _p)] = _net


def label_len(net):
    return 4.5 if net == "GND" else 1.0 * len(net) + 1.5


def extent(ref, sym, val=""):
    """Bounding box (x0, y0, x1, y1) relative to the symbol origin, schematic coordinates (y down)."""
    xs, ys = [-2.54, 2.54], [-2.54, 2.54]
    for n, (px, py, pang) in lib_pins(sym).items():
        x, y, out = pin_world(0, 0, px, py, pang)
        net = NETMAP.get((ref, n))
        reach = STUB + (label_len(net) if net else 1.0)
        xs += [x, x + out[0] * reach]
        ys += [y, y + out[1] * reach]
        if out[0]:                                 # horizontal label: text height
            ys += [y - 1.6, y + 1.6]
        else:
            xs += [x - 1.6, x + 1.6]
    half = 0.55 * max(len(val), len(ref)) + 0.5        # value / reference text centred on the symbol
    xs += [-half, half]
    return min(xs) - 1.27, min(ys) - 4.5, max(xs) + 1.27, max(ys) + 4.5


BLOCKS = SCH["blocks"]   # (title, x, y, width, refs) on an A2 sheet (594 x 420 mm)


def connect(ref, pins):
    for n, (x, y, out) in pins.items():
        net = NETMAP.get((ref, n))
        if net is None:
            if n in [str(p) for p in NO_CONNECT.get(ref, [])]:
                no_connect(x, y)
            continue
        ex, ey = x + out[0] * STUB, y + out[1] * STUB
        wire(x, y, ex, ey)
        if net == "GND":
            gnd(ex, ey, out)
        else:
            label(net, ex, ey, out)


def snap(v):
    return round(v / 1.27) * 1.27


def build():
    P = parts()
    placed = set()
    for title, bx, by, bw, refs in BLOCKS:
        note(title, bx, by - 8, 1.8)
        x, y, row_h = bx, by, 0.0
        for ref in refs:
            sym, val, fp = P[ref]
            x0, y0, x1, y1 = extent(ref, sym, val)
            w, h = x1 - x0, y1 - y0
            if x + w > bx + bw and x > bx:
                x, y, row_h = bx, y + row_h + 2.54, 0.0
            sx, sy = snap(x - x0), snap(y - y0)
            pins = place_symbol(ref, sym, val, fp, sx, sy, dnp=ref in DNP,
                                ref_at=(sx, snap(sy + y0 + 2.5)), val_at=(sx, snap(sy + y1 - 2.5)))
            connect(ref, pins)
            placed.add(ref)
            x += w + 2.54
            row_h = max(row_h, h)
    missing = set(P) - placed
    if missing:
        sys.exit(f"parts not placed: {sorted(missing)}")
    for k, net in enumerate(SCH["flags"]):
        pwr_flag(500.38 + 15.24 * k, 320.04, net)
    if PINMAP:
        rows = ["Pico 2 W pin map (GP -> net)"] + [f"GP{gp:<2} {net}" for gp, net in PINMAP.items()]
        note(chr(10).join(rows), 500, 30, 1.27)
    for txt, x, y, size in SCH["notes"]:
        note(txt, x, y, size)


def write():
    build()
    libsyms = "\n".join(lib_symbol_text(l) for l in sorted(lib_ids))
    libsyms = "\n".join("    " + ln for ln in libsyms.splitlines())
    sch = f'''(kicad_sch (version 20230121) (generator eeschema)

  (uuid {ROOT})

  (paper "A2")

  (title_block
    (title "{SCH['title']}")
    (date "{DATE}")
    (rev "{REVISION}")
    (company "KiCad-Designs")
    (comment 1 "{SCH['comment']}")
    (comment 2 "Generated by tools/gen_schematic.py from tools/{_M.__name__}.py - do not edit by hand")
  )

  (lib_symbols
{libsyms}
  )

{chr(10).join(items)}

  (sheet_instances
    (path "/" (page "1"))
  )
)
'''
    with open(os.path.join(PRJ, SCH["out"][0], SCH["out"][1] + ".kicad_sch"), "w", encoding="utf8", newline="\n") as f:
        f.write(sch)
    print(f"schematic written: {len(parts())} parts, {len(items)} items, {len(lib_ids)} library symbols")


if __name__ == "__main__":
    write()
