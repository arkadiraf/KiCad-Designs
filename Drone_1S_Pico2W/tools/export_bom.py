#!/usr/bin/env python3
"""Write the orderable BOM from design.FRAME_BOM + parts.py:

    fabrication/BOM_DigiKey.csv   upload to the Digi-Key BOM Manager (or Mouser BOM tool)
    fabrication/BOM.md            the same as a table, with status and notes
    fabrication/BOM_FC.xlsx       flight-controller order (x FC_ORDER_BOARDS)
    fabrication/BOM_Frame.xlsx    frame order (x FRAME_ORDER_BOARDS) with a Digi-Key cart and a stock sheet

Checks that every FRAME_BOM line has an MPN entry (prints BOM EXPORT OK).
Quantities are for ONE drone. DNP lines are listed with quantity 0.
"""
import csv
import os
import sys

from design import FRAME_BOM
from parts import CABLE_PARTS, DECK_PARTS, DIGIKEY, FC_PARTS, FRAME_MPN, FRAME_PLACED, MECH_PARTS

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "fabrication")


BOOK_PREFIX = ("RC0603", "GRM188", "CL10",   # 0603 resistors (Yageo) and capacitors (Murata, Samsung)
               "LTST-C171")                  # 0805 LEDs
# The user fits 0603 resistors / capacitors from a sample book and 0805 LEDs from stock: these are left out
# of the Digi-Key order and listed by value in fabrication/BOM_stock.md. E96 values get an E24 fallback.
E24_FALLBACK = {
    "226": "240 R (E24): ICHG 2.82 A (2.66-2.98 A), stays under the 3.0 A limit; 220 R would exceed it",
    "5.23k": "5.1k with 30k: TS window ~2-61 C",
    "30.9k": "30k with 5.1k: TS window ~2-61 C",
    "156k / 100k / 1.27M": "DNP option; E24 150k / 100k / 1.2M shifts the 2.70 / 3.30 V thresholds - recompute if fitted",
}


def is_book(mpn):
    return mpn.startswith(BOOK_PREFIX)


def rows():
    out, missing = [], []
    for refs, val, _sym, fp, role in FRAME_BOM:
        if refs not in FRAME_MPN:
            missing.append(refs)
            continue
        mfr, mpn, status, note = FRAME_MPN[refs]
        qty = 0 if status == "DNP" else len(refs.split())
        out.append(("Frame", refs, qty, f"{val} ({fp.split(':')[1]})", role, mfr, mpn, status, note))
    for board, lst in (("Frame", FRAME_PLACED), ("FC", FC_PARTS), ("Qwiic deck", DECK_PARTS), ("Cable", CABLE_PARTS),
                       ("Mechanical", MECH_PARTS)):
        for refs, qty, val, (mfr, mpn, status, note) in lst:
            out.append((board, refs, 0 if status == "DNP" else qty, val, "", mfr, mpn, status, note))
    return out, missing


def main():
    rs, missing = rows()
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, "BOM_DigiKey.csv"), "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["Quantity", "Manufacturer", "Manufacturer Part Number", "Digi-Key Part Number",
                    "Customer Reference", "Description", "Status", "Note"])
        merged = {}                                   # one line per orderable MPN, refs joined
        for board, refs, qty, val, role, mfr, mpn, status, note in rs:
            if mfr == "any" or "xxxx" in mpn or " / " in mpn or is_book(mpn) or note.startswith("local:"):
                continue                              # generic hardware, value open, multi-part DNP option, local supplier
            k = (mfr, mpn)
            if k in merged:
                m = merged[k]
                m[0] += qty
                m[3] += f", {board} {refs}"
            else:
                merged[k] = [qty, mfr, mpn, f"{board} {refs}", f"{val}; {role}".strip("; "), status, note]
        for m in merged.values():
            dk, life = DIGIKEY.get(m[2], ("", ""))
            w.writerow(m[:3] + [dk, m[3], m[4], m[5], "; ".join(x for x in (m[6], life) if x)])
    with open(os.path.join(OUT, "BOM.md"), "w") as f:
        f.write("# BOM - Drone_1S_Pico2W (one drone)\n\nGenerated by tools/export_bom.py from design.py + parts.py. "
                "MPNs not yet checked against Digi-Key / Mouser stock (sites blocked from the build container). "
                "The Bitcraze Flow deck v2 is ordered from Bitcraze.\n\n"
                "| Board | Refs | Qty | Part | Manufacturer | MPN | Digi-Key PN | Status | Note |\n|---|---|---|---|---|---|---|---|---|\n")
        for board, refs, qty, val, role, mfr, mpn, status, note in rs:
            dk, life = DIGIKEY.get(mpn, ("", ""))
            note = "; ".join(x for x in (note, life) if x)
            f.write(f"| {board} | {refs} | {qty} | {val} | {mfr} | `{mpn}` | {'`'+dk+'`' if dk else '—'} | {status} | {note} |\n")
    write_book(rs)
    write_to_source(rs)
    write_fc_xlsx(rs)
    write_frame_xlsx(rs)
    n = {s: sum(1 for r in rs if r[7] == s) for s in ("ok", "verify", "TBD", "DNP")}
    print(f"{len(rs)} BOM lines: {n}; missing MPN for {missing or 'none'}")
    print("BOM EXPORT OK" if not missing else "BOM EXPORT FAIL")
    return 0 if not missing else 1


FC_ORDER_BOARDS = 5                   # FC modules to order for (the user's Digi-Key cart is for 5)
FC_XLSX_EXTRA = {("Frame", "J5 J6"), ("Mechanical", "FC stack")}   # FC-related lines kept from other groups
FRAME_ORDER_BOARDS = 5                # frames to order for (user, 28 Nov: 5 of each board)
FRAME_XLSX_SKIP = {("Mechanical", "FC stack")}                      # in BOM_FC.xlsx


def source_of(mpn, status, note, dk):
    if status == "DNP":
        return "DNP"
    if mpn.startswith("3D-printed"):
        return "printed"
    if note.startswith("local:"):
        return "local"
    if is_book(mpn):
        return "stock"
    return "Digi-Key" if dk else "to source"


def write_order_xlsx(rs, fname, title, keep, boards, cart=False):
    """An order workbook: sheet 1 every line (per drone and x `boards`, Digi-Key PN, source); with cart=True also a
    'Digi-Key cart' sheet (one line per Digi-Key PN, quantities summed) and a 'Stock' sheet (sample-book values)."""
    try:
        import openpyxl
        from openpyxl.styles import Alignment, Font, PatternFill
    except ImportError:
        print(f"{fname} skipped (pip install openpyxl)")
        return
    hfont, hfill = Font(bold=True, color="FFFFFF"), PatternFill("solid", fgColor="44546A")
    fills = {"Digi-Key": None, "stock": "E2EFDA", "to source": "FCE4D6", "DNP": "EDEDED", "printed": "DDEBF7", "local": "DDEBF7"}

    def header(ws, head, widths):
        ws.append(head)
        hr = ws.max_row
        for c in ws[hr]:
            c.font, c.fill = hfont, hfill
        for k, w in enumerate(widths):
            ws.column_dimensions[chr(65 + k)].width = w
        ws.freeze_panes = f"A{hr + 1}"                  # (ws.cell() here would create a row and push data down)
        return hr

    def finish(ws, hr):
        for row in ws.iter_rows(min_row=hr + 1):
            for c in row:
                c.alignment = Alignment(wrap_text=True, vertical="top")

    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "Order"
    ws.append([f"Drone_1S_Pico2W - {title}, generated by tools/export_bom.py from tools/design.py + tools/parts.py"])
    ws["A1"].font = Font(bold=True, size=12)
    ws.append([f"Order quantity = per drone x {boards}. Source: Digi-Key (PN given), stock (0603 sample book / 0805 LEDs), "
               "to source (no Digi-Key PN yet), printed (3D-printed part), local (local supplier, see note), "
               "DNP = footprint only (order optional)."])
    ws.append([])
    hr = header(ws, ["Board", "Refs", "Part", "Manufacturer", "MPN", "Digi-Key PN", "Qty / drone", f"Qty x {boards}",
                     "Source", "Status", "Note"], (11, 14, 46, 22, 22, 24, 11, 9, 11, 8, 70))
    carts, stock = {}, {}
    for board, refs, qty, val, role, mfr, mpn, status, note in rs:
        if not keep(board, refs):
            continue
        dk, life = DIGIKEY.get(mpn, ("", ""))
        src = source_of(mpn, status, note, dk)
        per = len(refs.split()) if status == "DNP" else qty     # DNP lines: footprint count, order optional
        allnote = "; ".join(x for x in (note, life) if x)
        ws.append([board, refs, val, mfr, mpn if mfr != "any" else "", dk, per, per * boards, src, status, allnote])
        if fills[src]:
            for c in ws[ws.max_row]:
                c.fill = PatternFill("solid", fgColor=fills[src])
        if src == "Digi-Key":
            c = carts.setdefault(dk, [mfr, mpn, val, 0, [], allnote])
            c[3] += per * boards
            c[4].append(f"{board} {refs}")
        elif src == "stock":
            kind = "Resistor 0603" if mpn.startswith("RC0603") else "LED 0805" if mpn.startswith("LTST") else "Capacitor 0603"
            g = stock.setdefault((kind, val.split(" (")[0]), [0, []])
            g[0] += per * boards
            g[1].append(refs)
    n_order = ws.max_row - hr
    finish(ws, hr)
    if cart:
        wc = wb.create_sheet("Digi-Key cart")
        wc.append([f"One line per Digi-Key part number, for {boards} drones (no spares added). Paste PN + quantity into "
                   "the Digi-Key cart or upload this sheet to the BOM Manager."])
        wc.append([])
        h2 = header(wc, ["Digi-Key PN", "Quantity", "Manufacturer", "MPN", "Part", "Used on", "Note"],
                    (26, 10, 22, 26, 46, 30, 60))
        for dk, (mfr, mpn, val, q, used, note) in carts.items():
            wc.append([dk, q, mfr, mpn, val, ", ".join(used), note])
        finish(wc, h2)
        wst = wb.create_sheet("Stock")
        wst.append([f"Sample-book 0603 R / C and 0805 LEDs, for {boards} drones (not ordered; E24 fallbacks in BOM_stock.md)."])
        wst.append([])
        h3 = header(wst, ["Kind", "Value", "Quantity", "Refs"], (16, 30, 10, 50))
        for (kind, v), (q, refs) in sorted(stock.items()):
            wst.append([kind, v, q, ", ".join(refs)])
        finish(wst, h3)
    wb.save(os.path.join(OUT, fname))
    extra = f", cart {len(carts)} Digi-Key PNs, stock {len(stock)} values" if cart else ""
    print(f"{fname}: {n_order} lines for {boards}{extra}")


def write_fc_xlsx(rs, boards=FC_ORDER_BOARDS):
    """fabrication/BOM_FC.xlsx: the flight-controller order (FC parts + the frame's mating sockets J5/J6, the FC
    stack hardware), per drone and for `boards` modules."""
    write_order_xlsx(rs, "BOM_FC.xlsx", "flight controller parts",
                     lambda b, r: b in ("FC", "Qwiic deck") or (b, r) in FC_XLSX_EXTRA, boards)


def write_frame_xlsx(rs, boards=FRAME_ORDER_BOARDS):
    """fabrication/BOM_Frame.xlsx: the frame (power board) order - its electrical parts, the placed connectors
    (ESC seats, J5/J6 sockets, J7/J8), the cable mates and the frame hardware - plus a Digi-Key cart and stock sheet."""
    write_order_xlsx(rs, "BOM_Frame.xlsx", "frame (power board) parts",
                     lambda b, r: b in ("Frame", "Cable", "Mechanical") and (b, r) not in FRAME_XLSX_SKIP, boards, cart=True)


def write_to_source(rs):
    """Everything that still needs a Digi-Key (or other distributor) part number: no DK PN and not stock."""
    lines = ["# Parts still to source (no Digi-Key part number yet)", "",
             "Generated by tools/export_bom.py. Fill the Digi-Key number into `DIGIKEY` (or the MPN into `MECH_PARTS` / "
             "`CABLE_PARTS`) in tools/parts.py and regenerate. Quantities are for one drone.", "",
             "| Group | Refs / use | Qty | Part / spec | Manufacturer | MPN | Status | Note |", "|---|---|---|---|---|---|---|---|"]
    n = 0
    for board, refs, qty, val, role, mfr, mpn, status, note in rs:
        if is_book(mpn) or mpn.startswith("3D-printed") or note.startswith("local:") or status == "DNP" and mfr != "JST":
            continue
        dk, life = DIGIKEY.get(mpn, ("", ""))
        if dk:
            continue
        n += 1
        lines.append(f"| {board} | {refs} | {qty} | {val.split(' (')[0] if board == 'Frame' else val} | {mfr} | "
                     f"{'`' + mpn + '`' if mfr != 'any' else '—'} | {status} | {'; '.join(x for x in (note, life) if x)} |")
    with open(os.path.join(OUT, "BOM_to_source.md"), "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"to source: {n} lines")


def write_book(rs):
    """0603 R / C from the sample book, grouped by kind and value."""
    groups = {}
    for board, refs, qty, val, role, mfr, mpn, status, note in rs:
        if not is_book(mpn):
            continue
        kind = "Resistor 0603" if mpn.startswith("RC0603") else "LED 0805" if mpn.startswith("LTST") else "Capacitor 0603"
        v = val.split(" (")[0]
        key = (kind, v)
        g = groups.setdefault(key, [0, [], set(), []])
        g[0] += qty
        g[1].append(f"{board} {refs}")
        g[2].add(status)
        g[3].append(role or note)
    lines = ["# Stock parts: 0603 resistors / capacitors (sample book) and 0805 LEDs", "",
             "Generated by tools/export_bom.py. These are not in BOM_DigiKey.csv. Quantities are for one drone "
             "(DNP = footprint only). Resistors 1 %, 0603; capacitors X5R/X7R 0603 with at least the voltage shown; "
             "LEDs 0805.",
             "", "| Kind | Value | Qty | Refs | Status | Use | E24 fallback if the book lacks it |", "|---|---|---|---|---|---|---|"]
    for (kind, v), (qty, refs, st, use) in sorted(groups.items()):
        fb = next((t for k, t in E24_FALLBACK.items() if v.startswith(k)), "")
        lines.append(f"| {kind} | {v} | {qty} | {', '.join(refs)} | {'/'.join(sorted(st))} | {'; '.join(dict.fromkeys(u for u in use if u))} | {fb} |")
    with open(os.path.join(OUT, "BOM_stock.md"), "w") as f:
        f.write("\n".join(lines) + "\n")
    with open(os.path.join(OUT, "BOM_stock.csv"), "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["Kind", "Value", "Quantity", "Refs", "Status"])
        for (kind, v), (qty, refs, st, use) in sorted(groups.items()):
            w.writerow([kind, v, qty, ", ".join(refs), "/".join(sorted(st))])
    print(f"stock list: {len(groups)} values, {sum(g[0] for g in groups.values())} parts")


if __name__ == "__main__":
    sys.exit(main())
