#!/usr/bin/env python3
"""Write the orderable BOM from design.FRAME_BOM + parts.py:

    fabrication/BOM_DigiKey.csv   upload to the Digi-Key BOM Manager (or Mouser BOM tool)
    fabrication/BOM.md            the same as a table, with status and notes

Checks that every FRAME_BOM line has an MPN entry (prints BOM EXPORT OK).
Quantities are for ONE drone. DNP lines are listed with quantity 0.
"""
import csv
import os
import sys

from design import FRAME_BOM
from parts import CABLE_PARTS, DIGIKEY, FC_PARTS, FRAME_MPN, FRAME_PLACED, MECH_PARTS

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "fabrication")


BOOK_PREFIX = ("RC0603", "GRM188", "CL10",   # 0603 resistors (Yageo) and capacitors (Murata, Samsung)
               "LTST-C171")                  # 0805 LEDs
# The user fits 0603 resistors / capacitors from a sample book and 0805 LEDs from stock: these are left out
# of the Digi-Key order and listed by value in fabrication/BOM_stock.md. E96 values get an E24 fallback.
E24_FALLBACK = {
    "226": "240 R (E24): ICHG 2.82 A (2.66-2.98 A), stays under the 3.0 A limit; 220 R would exceed it",
    "5.23k": "5.1k with 30k: TS window ~2-61 C",
    "30.9k": "30k with 5.1k: TS window ~2-61 C",
    "156k / 100k / 1.27M": "DNP option; E24 150k / 100k / 1.2M shifts the 2.70 / 3.30 V thresholds - recompute if fitted",
}


def is_book(mpn):
    return mpn.startswith(BOOK_PREFIX)


def rows():
    out, missing = [], []
    for refs, val, _sym, fp, role in FRAME_BOM:
        if refs not in FRAME_MPN:
            missing.append(refs)
            continue
        mfr, mpn, status, note = FRAME_MPN[refs]
        qty = 0 if status == "DNP" else len(refs.split())
        out.append(("Frame", refs, qty, f"{val} ({fp.split(':')[1]})", role, mfr, mpn, status, note))
    for board, lst in (("Frame", FRAME_PLACED), ("FC", FC_PARTS), ("Cable", CABLE_PARTS), ("Mechanical", MECH_PARTS)):
        for refs, qty, val, (mfr, mpn, status, note) in lst:
            out.append((board, refs, 0 if status == "DNP" else qty, val, "", mfr, mpn, status, note))
    return out, missing


def main():
    rs, missing = rows()
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, "BOM_DigiKey.csv"), "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["Quantity", "Manufacturer", "Manufacturer Part Number", "Digi-Key Part Number",
                    "Customer Reference", "Description", "Status", "Note"])
        merged = {}                                   # one line per orderable MPN, refs joined
        for board, refs, qty, val, role, mfr, mpn, status, note in rs:
            if mfr == "any" or "xxxx" in mpn or " / " in mpn or is_book(mpn):
                continue                              # generic hardware, value still open, or a multi-part DNP option
            k = (mfr, mpn)
            if k in merged:
                m = merged[k]
                m[0] += qty
                m[3] += f", {board} {refs}"
            else:
                merged[k] = [qty, mfr, mpn, f"{board} {refs}", f"{val}; {role}".strip("; "), status, note]
        for m in merged.values():
            dk, life = DIGIKEY.get(m[2], ("", ""))
            w.writerow(m[:3] + [dk, m[3], m[4], m[5], "; ".join(x for x in (m[6], life) if x)])
    with open(os.path.join(OUT, "BOM.md"), "w") as f:
        f.write("# BOM - Drone_1S_Pico2W (one drone)\n\nGenerated by tools/export_bom.py from design.py + parts.py. "
                "MPNs not yet checked against Digi-Key / Mouser stock (sites blocked from the build container). "
                "The Bitcraze Flow deck v2 is ordered from Bitcraze.\n\n"
                "| Board | Refs | Qty | Part | Manufacturer | MPN | Digi-Key PN | Status | Note |\n|---|---|---|---|---|---|---|---|---|\n")
        for board, refs, qty, val, role, mfr, mpn, status, note in rs:
            dk, life = DIGIKEY.get(mpn, ("", ""))
            note = "; ".join(x for x in (note, life) if x)
            f.write(f"| {board} | {refs} | {qty} | {val} | {mfr} | `{mpn}` | {'`'+dk+'`' if dk else '—'} | {status} | {note} |\n")
    write_book(rs)
    write_to_source(rs)
    n = {s: sum(1 for r in rs if r[7] == s) for s in ("ok", "verify", "TBD", "DNP")}
    print(f"{len(rs)} BOM lines: {n}; missing MPN for {missing or 'none'}")
    print("BOM EXPORT OK" if not missing else "BOM EXPORT FAIL")
    return 0 if not missing else 1


def write_to_source(rs):
    """Everything that still needs a Digi-Key (or other distributor) part number: no DK PN and not stock."""
    lines = ["# Parts still to source (no Digi-Key part number yet)", "",
             "Generated by tools/export_bom.py. Fill the Digi-Key number into `DIGIKEY` (or the MPN into `MECH_PARTS` / "
             "`CABLE_PARTS`) in tools/parts.py and regenerate. Quantities are for one drone.", "",
             "| Group | Refs / use | Qty | Part / spec | Manufacturer | MPN | Status | Note |", "|---|---|---|---|---|---|---|---|"]
    n = 0
    for board, refs, qty, val, role, mfr, mpn, status, note in rs:
        if is_book(mpn) or status == "DNP" and mfr != "JST":
            continue
        dk, life = DIGIKEY.get(mpn, ("", ""))
        if dk:
            continue
        n += 1
        lines.append(f"| {board} | {refs} | {qty} | {val.split(' (')[0] if board == 'Frame' else val} | {mfr} | "
                     f"{'`' + mpn + '`' if mfr != 'any' else '—'} | {status} | {'; '.join(x for x in (note, life) if x)} |")
    with open(os.path.join(OUT, "BOM_to_source.md"), "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"to source: {n} lines")


def write_book(rs):
    """0603 R / C from the sample book, grouped by kind and value."""
    groups = {}
    for board, refs, qty, val, role, mfr, mpn, status, note in rs:
        if not is_book(mpn):
            continue
        kind = "Resistor 0603" if mpn.startswith("RC0603") else "LED 0805" if mpn.startswith("LTST") else "Capacitor 0603"
        v = val.split(" (")[0]
        key = (kind, v)
        g = groups.setdefault(key, [0, [], set(), []])
        g[0] += qty
        g[1].append(f"{board} {refs}")
        g[2].add(status)
        g[3].append(role or note)
    lines = ["# Stock parts: 0603 resistors / capacitors (sample book) and 0805 LEDs", "",
             "Generated by tools/export_bom.py. These are not in BOM_DigiKey.csv. Quantities are for one drone "
             "(DNP = footprint only). Resistors 1 %, 0603; capacitors X5R/X7R 0603 with at least the voltage shown; "
             "LEDs 0805.",
             "", "| Kind | Value | Qty | Refs | Status | Use | E24 fallback if the book lacks it |", "|---|---|---|---|---|---|---|"]
    for (kind, v), (qty, refs, st, use) in sorted(groups.items()):
        fb = next((t for k, t in E24_FALLBACK.items() if v.startswith(k)), "")
        lines.append(f"| {kind} | {v} | {qty} | {', '.join(refs)} | {'/'.join(sorted(st))} | {'; '.join(dict.fromkeys(u for u in use if u))} | {fb} |")
    with open(os.path.join(OUT, "BOM_stock.md"), "w") as f:
        f.write("\n".join(lines) + "\n")
    with open(os.path.join(OUT, "BOM_stock.csv"), "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["Kind", "Value", "Quantity", "Refs", "Status"])
        for (kind, v), (qty, refs, st, use) in sorted(groups.items()):
            w.writerow([kind, v, qty, ", ".join(refs), "/".join(sorted(st))])
    print(f"stock list: {len(groups)} values, {sum(g[0] for g in groups.values())} parts")


if __name__ == "__main__":
    sys.exit(main())
