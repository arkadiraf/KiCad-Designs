#!/usr/bin/env python3
"""Stock passives (0603 R / C from the sample book, 0805 LEDs) for all the boards in this repository, x boards.

    python Orders/stock_passives.py [boards=5] [out_dir=Orders/<today>]

Reads each project's fabrication/BOM_stock.csv (written by its tools/export_bom.py: regenerate those first). The drone
list is per drone = frame + FC + Qwiic deck. Pico_Alvik_Adapter has no stock passives (its only passive, a 0805
10 uF, is in the Digi-Key order). Writes Stock_passives.xlsx (a checklist with a "have" column) and Stock_passives.md.
"""
import csv
import datetime
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PROJECTS = [("Drone_1S_Pico2W", "Drone"), ("PicoBalancer", "PicoBalancer")]
SPARES = 0.2                     # suggested spare fraction for hand assembly (dropped / tombstoned parts), at least +2

# E96 values a sample book may lack: the E24 part that still works (from the projects' export_bom.py notes)
E24 = {
    "226": "240 (ICHG 2.82 A instead of 3.0 A; 220 would exceed the 3.0 A limit)",
    "5.23k": "5.1k, together with 30k for 30.9k (TS window ~2-61 C)",
    "30.9k": "30k, together with 5.1k for 5.23k",
    "49.9k": "51k (boost current limit 2.44 A instead of 2.49 A)",
    "156k": "150k (PicoBalancer UVLO; thresholds shift - recompute)",
    "1.27M": "1.2M (PicoBalancer UVLO hysteresis; recompute)",
    "4.3k": "4.7k lowers the MP6550 limit to ~1.06 A; 3.9k raises it to ~1.28 A - check against the motor",
}


def ohms(v):
    m = re.match(r"([\d.]+)\s*([kKM]?)", v)
    return float(m.group(1)) * {"": 1, "k": 1e3, "K": 1e3, "M": 1e6}[m.group(2)] if m else 0


def farads(v):
    m = re.match(r"([\d.]+)\s*([pnu])F", v)
    return float(m.group(1)) * {"p": 1e-12, "n": 1e-9, "u": 1e-6}[m.group(2)] if m else 0


def clean(kind, value):
    v = re.sub(r"\s*0603|\s*0805|\s*\(DNP\)", "", value).strip()
    if kind.startswith("Resistor"):
        v = re.sub(r"(\d)R$", r"\1", v)             # "100R" -> "100", keep "0R"
        v = "0R" if v in ("0", "0R") else v
    return v


def rows(boards):
    items = {}                                       # (kind, value) -> {project: qty, refs..., dnp}
    for proj, short in PROJECTS:
        with open(os.path.join(ROOT, proj, "fabrication", "BOM_stock.csv"), newline="", encoding="utf-8-sig") as f:
            for r in csv.DictReader(f):
                kind, status = r["Kind"], r["Status"]
                values = [clean(kind, v) for v in r["Value"].split(" / ")]
                refs = r["Refs"].replace(",", "").split()
                for k, v in enumerate(values):
                    dnp = status == "DNP" or int(r["Quantity"]) == 0
                    n = int(r["Quantity"]) if len(values) == 1 else 1
                    if dnp:
                        n = len(values) == 1 and len([x for x in refs if re.match(r"[A-Z]+\d", x)]) or 1
                    it = items.setdefault((kind, v), dict(need={p: 0 for _, p in PROJECTS},
                                                          dnp={p: 0 for _, p in PROJECTS}, refs=[]))
                    (it["dnp"] if dnp else it["need"])[short] += n * boards
                    rr = refs[k:k + 1] if len(values) > 1 else refs
                    it["refs"].append(f"{short}: {' '.join(rr)}" + (" (DNP)" if dnp else ""))
    order = {"Resistor 0603": 0, "Capacitor 0603": 1, "LED 0805": 2}
    key = lambda kv: (order.get(kv[0][0], 9), ohms(kv[0][1]) if kv[0][0].startswith("Res") else
                      farads(kv[0][1]) if kv[0][0].startswith("Cap") else 0, kv[0][1])
    return sorted(items.items(), key=key)


def main():
    boards = int(sys.argv[1]) if len(sys.argv) > 1 else 5
    out_dir = sys.argv[2] if len(sys.argv) > 2 else os.path.join(ROOT, "Orders", datetime.date.today().isoformat())
    os.makedirs(out_dir, exist_ok=True)
    data = rows(boards)
    names = [p for _, p in PROJECTS]
    table = []
    for (kind, v), it in data:
        need = sum(it["need"].values())
        dnp = sum(it["dnp"].values())
        spare = max(2, round(need * SPARES)) if need else 0
        fb = E24.get(v, "") if kind.startswith("Resistor") else ""
        if kind.startswith("Capacitor"):
            fb = "X7R / X5R, at least the voltage shown (higher is fine)"
        table.append((kind, v, *[it["need"][p] for p in names], need, need + spare, dnp, "; ".join(it["refs"]), fb))

    try:
        import openpyxl
        from openpyxl.styles import Alignment, Font, PatternFill
        wb = openpyxl.Workbook()
        ws = wb.active
        ws.title = "Stock passives"
        ws.append([f"Stock passives for {boards} of each board (Drone_1S_Pico2W = frame + FC + Qwiic deck; "
                   f"PicoBalancer). Pico_Alvik_Adapter: none. Generated by Orders/stock_passives.py."])
        ws["A1"].font = Font(bold=True, size=12)
        ws.append(["Fill 'Have' from the sample book; 'With spares' adds ~20 % (at least 2) for hand-assembly losses. "
                   "DNP = footprint only, not needed."])
        ws.append([])
        head = ["Kind", "Value", *[f"{p} x{boards}" for p in names], "Need", "With spares", "DNP (optional)",
                "Have", "Enough?", "Refs", "Substitute if missing"]
        ws.append(head)
        for c in ws[4]:
            c.font, c.fill = Font(bold=True, color="FFFFFF"), PatternFill("solid", fgColor="44546A")
        for t in table:
            ws.append(list(t[:-2]) + [None, None, t[-2], t[-1]])
            r = ws.max_row
            have, need = f"{chr(65 + 2 + len(names) + 3)}{r}", f"{chr(65 + 2 + len(names))}{r}"
            ws[f"{chr(65 + 2 + len(names) + 4)}{r}"] = f'=IF({have}="","",IF({have}>={need},"yes","NO"))'
            if t[0].startswith("Capacitor"):
                for c in ws[r]:
                    c.fill = PatternFill("solid", fgColor="E2EFDA")
            elif t[0].startswith("LED"):
                for c in ws[r]:
                    c.fill = PatternFill("solid", fgColor="FFF2CC")
        for k, w in enumerate((15, 12, *[13] * len(names), 7, 11, 10, 8, 9, 60, 50)):
            ws.column_dimensions[chr(65 + k)].width = w
        for row in ws.iter_rows(min_row=5):
            for c in row:
                c.alignment = Alignment(wrap_text=True, vertical="top")
        ws.freeze_panes = "C5"
        wb.save(os.path.join(out_dir, "Stock_passives.xlsx"))
    except ImportError:
        print("Stock_passives.xlsx skipped (pip install openpyxl)")

    md = [f"# Stock passives, {boards} of each board", "",
          "Generated by `Orders/stock_passives.py` from each project's `fabrication/BOM_stock.csv`. Drone = frame + FC + "
          "Qwiic deck; Pico_Alvik_Adapter has none. Capacitors: X7R / X5R with at least the voltage shown. "
          "\"With spares\" adds ~20 % (at least 2).", "",
          f"| Kind | Value | {' | '.join(names)} | Need | With spares | DNP | Substitute if missing |",
          "|---|---|" + "---|" * len(names) + "---|---|---|---|"]
    for t in table:
        md.append(f"| {t[0]} | {t[1]} | {' | '.join(str(x or '') for x in t[2:2 + len(names)])} | **{t[2 + len(names)]}** | "
                  f"{t[3 + len(names)]} | {t[4 + len(names)] or ''} | {t[-1] if t[0].startswith('Resistor') else ''} |")
    with open(os.path.join(out_dir, "Stock_passives.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(md) + "\n")
    tot = {k: sum(t[2 + len(names)] for t in table if t[0].startswith(k)) for k in ("Resistor", "Capacitor", "LED")}
    print(f"{out_dir}: {len(table)} values; parts needed {tot}")
    for t in table:
        print(f"  {t[0]:15} {t[1]:12} need {t[2 + len(names)]:>3}  spares {t[3 + len(names)]:>3}"
              + (f"  DNP {t[4 + len(names)]}" if t[4 + len(names)] else ""))


if __name__ == "__main__":
    sys.exit(main())
