#!/usr/bin/env python3
"""Write Materials/bom_datasheets/README.md: every orderable part with its Digi-Key PN, datasheet file(s)
and verification result (from parts.DATASHEETS). Prints a summary."""
import os

from export_bom import is_stock, rows
from parts import DATASHEETS, DIGIKEY

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DIR = os.path.join(ROOT, "Materials", "bom_datasheets")


def main():
    rs, _ = rows()
    seen = {}
    for refs, qty, val, fp, role, mfr, mpn, status, note in rs:
        if mfr in ("any", "-"):
            continue
        for m in [x.strip() for x in mpn.split(" / ")]:
            if m.startswith("-"):
                m = "RC0603FR" + m
            seen.setdefault(m, [mfr, []])[1].append(refs)
    n = dict(ok=0, open=0, none=0, stock=0)
    lines = []
    for m, (mfr, where) in seen.items():
        dk, life = DIGIKEY.get(m, ("", ""))
        docs = DATASHEETS.get(m, [])
        files = [f"[{os.path.basename(f)}]({f})" + ("" if os.path.exists(os.path.join(DIR, f)) else " (missing)")
                 for f, _ in docs]
        result = " / ".join(r for _, r in docs)
        if not docs and is_stock(m):
            result, k = "stock part, no datasheet needed", "stock"
        elif not docs:
            result, k = "no datasheet yet", "none"
        else:
            k = "open" if "OPEN" in result or "PARTLY" in result else "ok"
        n[k] += 1
        lines.append(f"| `{m}` | {mfr} | {', '.join(where)} | {'`' + dk + '`' if dk else '—'} | {life} | "
                     f"{'<br>'.join(files) or '—'} | {result} |")
    with open(os.path.join(DIR, "README.md"), "w", encoding="utf-8") as f:
        f.write("# BOM datasheets and part verification\n\nGenerated by `tools/datasheet_index.py` from "
                "`tools/parts.py`. Drop each datasheet here as `<MPN>_<maker>_<kind>.pdf`, add it to `DATASHEETS` "
                "with what it confirmed, and regenerate.\n\n"
                f"Status: {n['ok']} verified, {n['open']} with OPEN items, {n['none']} without a datasheet, "
                f"{n['stock']} stock parts.\n\n"
                "| MPN | Maker | Refs | Digi-Key PN | Note | Datasheet | Verification |\n|---|---|---|---|---|---|---|\n"
                + "\n".join(lines) + "\n")
    print(f"{len(seen)} parts: {n}")


if __name__ == "__main__":
    main()
