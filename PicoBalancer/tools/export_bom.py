#!/usr/bin/env python3
"""Write the orderable BOM from design.BOM + parts.py (one board):

    fabrication/BOM_DigiKey.csv   distributor upload (Digi-Key BOM Manager / Mouser BOM tool), stock parts excluded
    fabrication/BOM.md            every line with status and notes
    fabrication/BOM_stock.md/.csv 0603 R / C (sample book) and 0805 LEDs, grouped by value
    fabrication/BOM_to_source.md  lines with no distributor part number yet

Checks: every BOM line has an MPN entry, and the passives rule (R / C 0603, bulk >= 10 uF 0805 / 1206,
LEDs 0805). Prints BOM EXPORT OK.
"""
import csv
import os
import re
import sys

from design import BOM, PROJECT
from parts import DIGIKEY, EXTRA, MPN

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "fabrication")
STOCK_PREFIX = ("RC0603", "GRM188", "GRM1885", "CL10", "LTST-C171")


def is_stock(mpn):
    return mpn.startswith(STOCK_PREFIX)


def farads(val):
    m = re.match(r"\s*([\d.]+)\s*([pnu])F", val)
    return float(m.group(1)) * {"p": 1e-12, "n": 1e-9, "u": 1e-6}[m.group(2)] if m else None


def passive_rule(val, fp):
    if fp.startswith("LED_SMD:") and "0805" not in fp:
        return "LED not 0805"
    m = re.match(r"(?:Resistor|Capacitor)_SMD:([RC])_(\d{4})_", fp)
    if not m:
        return None
    kind, size = m.groups()
    if kind == "R":
        return None if size == "0603" else f"resistor {size}"
    f = farads(val)
    if f is not None and f >= 9.99e-6:
        return None if size in ("0805", "1206") else f"bulk capacitor {val} in {size}"
    return None if size == "0603" else f"capacitor {val} in {size}"


def rows():
    out, problems = [], []
    for refs, val, _sym, fp, role in BOM:
        if refs not in MPN:
            problems.append(f"{refs}: no MPN")
            continue
        why = passive_rule(val, fp)
        if why:
            problems.append(f"{refs}: passives rule, {why}")
        mfr, mpn, status, note = MPN[refs]
        qty = 0 if status == "DNP" else len(refs.split())
        out.append((refs, qty, val, fp.split(":")[-1], role, mfr, mpn, status, note))
    for refs, qty, val, (mfr, mpn, status, note) in EXTRA:
        out.append((refs, qty, val, "", "", mfr, mpn, status, note))
    return out, problems


def main():
    rs, problems = rows()
    os.makedirs(OUT, exist_ok=True)
    merged = {}
    for refs, qty, val, fp, role, mfr, mpn, status, note in rs:
        if mfr in ("any", "-") or " / " in mpn or is_stock(mpn) or status == "DNP" and mfr != "Sullins":
            continue
        k = (mfr, mpn)
        if k in merged:
            merged[k][0] += qty
            merged[k][3] += f" {refs}"
        else:
            merged[k] = [qty, mfr, mpn, refs, val, status, note]
    with open(os.path.join(OUT, "BOM_DigiKey.csv"), "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["Quantity", "Manufacturer", "Manufacturer Part Number", "Digi-Key Part Number",
                    "Customer Reference", "Description", "Status", "Note"])
        for m in merged.values():
            dk, life = DIGIKEY.get(m[2], ("", ""))
            w.writerow(m[:3] + [dk, m[3], m[4], m[5], "; ".join(x for x in (m[6], life) if x)])
    with open(os.path.join(OUT, "BOM.md"), "w", encoding="utf-8") as f:
        f.write(f"# BOM - {PROJECT} (one board)\n\nGenerated by tools/export_bom.py from design.py + parts.py. "
                "Supply: Digi-Key or Mouser, whichever has stock. Stock = 0603 R / C sample book and 0805 LEDs.\n\n"
                "| Refs | Qty | Part | Footprint | Manufacturer | MPN | Digi-Key PN | Status | Note |\n"
                "|---|---|---|---|---|---|---|---|---|\n")
        for refs, qty, val, fp, role, mfr, mpn, status, note in rs:
            dk, life = DIGIKEY.get(mpn, ("", ""))
            st = "stock" if is_stock(mpn) and status != "DNP" else status
            f.write(f"| {refs} | {qty} | {val} | {fp} | {mfr} | `{mpn}` | {'`' + dk + '`' if dk else '—'} | {st} | "
                    f"{'; '.join(x for x in (role, note, life) if x)} |\n")
    groups = {}
    for refs, qty, val, fp, role, mfr, mpn, status, note in rs:
        if not is_stock(mpn):
            continue
        kind = "Resistor 0603" if mpn.startswith("RC0603") else "LED 0805" if mpn.startswith("LTST") else "Capacitor 0603"
        g = groups.setdefault((kind, val), [0, [], set()])
        g[0] += qty
        g[1].append(refs)
        g[2].add(status)
    with open(os.path.join(OUT, "BOM_stock.md"), "w", encoding="utf-8") as f:
        f.write("# Stock parts: 0603 resistors / capacitors (sample book) and 0805 LEDs\n\nGenerated by "
                "tools/export_bom.py; not in BOM_DigiKey.csv. Resistors 1 %; capacitors X5R/X7R (C0G for pF) with at "
                "least the voltage shown.\n\n| Kind | Value | Qty | Refs | Status |\n|---|---|---|---|---|\n")
        for (kind, v), (qty, refs, st) in sorted(groups.items()):
            f.write(f"| {kind} | {v} | {qty} | {', '.join(refs)} | {'/'.join(sorted(st))} |\n")
    with open(os.path.join(OUT, "BOM_stock.csv"), "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["Kind", "Value", "Quantity", "Refs", "Status"])
        for (kind, v), (qty, refs, st) in sorted(groups.items()):
            w.writerow([kind, v, qty, ", ".join(refs), "/".join(sorted(st))])
    n_src = 0
    with open(os.path.join(OUT, "BOM_to_source.md"), "w", encoding="utf-8") as f:
        f.write("# Parts still to source (no Digi-Key part number yet)\n\nGenerated by tools/export_bom.py. Add the "
                "Digi-Key (or Mouser) number to `DIGIKEY` in tools/parts.py and regenerate.\n\n"
                "| Refs | Qty | Part | Manufacturer | MPN | Status | Note |\n|---|---|---|---|---|---|---|\n")
        for refs, qty, val, fp, role, mfr, mpn, status, note in rs:
            if is_stock(mpn) or status == "DNP" or mfr == "-" or DIGIKEY.get(mpn, ("",))[0]:
                continue
            n_src += 1
            f.write(f"| {refs} | {qty} | {val} | {mfr} | `{mpn}` | {status} | {note} |\n")
    n = {s: sum(1 for r in rs if r[7] == s) for s in ("ok", "verify", "TBD", "DNP")}
    print(f"{len(rs)} BOM lines {n}; {len(merged)} distributor lines, {n_src} to source, "
          f"{len(groups)} stock values ({sum(g[0] for g in groups.values())} parts)")
    for p in problems:
        print("  ", p)
    print("BOM EXPORT OK" if not problems else "BOM EXPORT FAIL")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
